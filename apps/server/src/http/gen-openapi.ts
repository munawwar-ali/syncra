/** Writes docs/openapi.yaml from the live operation table: `pnpm --filter @syncra/server gen:openapi`. */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { stringify } from 'yaml';
import { buildOpenApi } from './openapi.js';

const out = fileURLToPath(new URL('../../../../docs/openapi.yaml', import.meta.url));
writeFileSync(
  out,
  `# Generated by gen-openapi.ts from the route table and Zod schemas. Do not edit by hand.\n${stringify(buildOpenApi(), { lineWidth: 100 })}`,
);
console.log(`wrote ${out}`);
